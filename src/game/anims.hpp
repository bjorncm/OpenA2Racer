// mm_af_image / get_control_image_index: sprite of a frame of an animation.
inline int animSprite(int anim, int frame)
{
    const auto& table = animTable();
    if (anim < 0 || static_cast<std::size_t>(anim) >= table.size()) return -1;
    const auto& frames = table[static_cast<std::size_t>(anim)];
    if (frame < 0 || static_cast<std::size_t>(frame) >= frames.size()) return -1;
    return frames[static_cast<std::size_t>(frame)];
}

inline int animFrameCount(int anim)
{
    const auto& table = animTable();
    if (anim < 0 || static_cast<std::size_t>(anim) >= table.size()) return 0;
    return static_cast<int>(table[static_cast<std::size_t>(anim)].size());
}

